-- ===== 7. Draw and allotment functions =====

-- Draws the pick order once the pool has closed and creates the month's empty slots.
-- slots = days * 4, n = applicants:
--   floor(slots / n) full rounds, each a fresh shuffle of everyone,
--   + one round of the first (slots mod n) people of another shuffle.
-- The shuffle is md5(seed, round, user) so the same seed always gives the same order.
-- Can be redrawn (new seed) until the first pick is assigned.
CREATE OR REPLACE FUNCTION public.draw_reception_pool(p_pool_id bigint, p_seed bigint DEFAULT NULL)
RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.current_base_user_id();
    pool public.reception_pools;
    v_seed bigint := coalesce(p_seed, floor(random() * 1000000000)::bigint);
    n integer;
    total integer;
    full_rounds integer;
    rem integer;
    r integer;
    pos integer := 0;
    was_drawn boolean;
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za žreb.';
    END IF;

    SELECT * INTO pool FROM public.reception_pools WHERE id = p_pool_id FOR UPDATE;
    IF pool.id IS NULL THEN
        RAISE EXCEPTION 'Prijave ne obstajajo.';
    END IF;
    IF now() <= pool.closes_at THEN
        RAISE EXCEPTION 'Prijave so še odprte do %.', pool.closes_at;
    END IF;
    IF pool.status NOT IN ('open', 'drawn') THEN
        RAISE EXCEPTION 'Razdeljevanje se je že začelo, ponovni žreb ni mogoč.';
    END IF;

    SELECT count(*) INTO n FROM public.reception_applications WHERE pool_id = p_pool_id;
    IF n = 0 THEN
        RAISE EXCEPTION 'Ni prijavljenih.';
    END IF;

    total := extract(day FROM (pool.month + interval '1 month' - interval '1 day'))::integer * 4;
    full_rounds := total / n;
    rem := total % n;
    was_drawn := pool.status = 'drawn';

    DELETE FROM public.reception_pick_order WHERE pool_id = p_pool_id;

    FOR r IN 1 .. full_rounds + (rem > 0)::integer LOOP
        INSERT INTO public.reception_pick_order (pool_id, position, round, user_id)
        SELECT p_pool_id, pos + s.rn, r, s.user_id
        FROM (
            SELECT a.user_id,
                   row_number() OVER (ORDER BY md5(v_seed || ':' || r || ':' || a.user_id), a.user_id) AS rn
            FROM public.reception_applications a
            WHERE a.pool_id = p_pool_id
        ) s
        WHERE s.rn <= CASE WHEN r > full_rounds THEN rem ELSE n END;
        pos := pos + CASE WHEN r > full_rounds THEN rem ELSE n END;
    END LOOP;

    -- the month's empty slots
    INSERT INTO public.dezurstva (date, slot, pool_id, created_by)
    SELECT d::date, s, p_pool_id, me
    FROM generate_series(pool.month, pool.month + interval '1 month' - interval '1 day', interval '1 day') d,
         generate_series(0, 3) s
    ON CONFLICT (date, slot) DO NOTHING;

    UPDATE public.reception_pools
    SET status = 'drawn', seed = v_seed, drawn_at = now(), drawn_by = me
    WHERE id = p_pool_id;

    INSERT INTO public.reception_draw_log (pool_id, actor, action, seed, details)
    VALUES (p_pool_id, me, CASE WHEN was_drawn THEN 'redraw' ELSE 'draw' END, v_seed,
            jsonb_build_object('applicants', n, 'slots', total, 'full_rounds', full_rounds, 'last_round', rem));

    RETURN v_seed;
END;
$$;

-- Manager swaps two positions in the order before picking starts (Žreb mockup)
CREATE OR REPLACE FUNCTION public.swap_reception_positions(p_pool_id bigint, p_a integer, p_b integer)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za urejanje vrstnega reda.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.reception_pools WHERE id = p_pool_id AND status = 'drawn') THEN
        RAISE EXCEPTION 'Vrstni red je mogoče urejati samo pred razdeljevanjem.';
    END IF;

    UPDATE public.reception_pick_order
    SET position = CASE position WHEN p_a THEN p_b ELSE p_a END
    WHERE pool_id = p_pool_id AND position IN (p_a, p_b);

    INSERT INTO public.reception_draw_log (pool_id, actor, action, details)
    VALUES (p_pool_id, public.current_base_user_id(), 'move', jsonb_build_object('a', p_a, 'b', p_b));
END;
$$;

-- Give the free slot to whoever is on turn, then the next person is on turn
CREATE OR REPLACE FUNCTION public.assign_reception_pick(p_pool_id bigint, p_dezurstvo_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    pk public.reception_pick_order;
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za razdeljevanje.';
    END IF;

    SELECT * INTO pk FROM public.reception_pick_order
    WHERE pool_id = p_pool_id AND status = 'pending'
    ORDER BY position LIMIT 1
    FOR UPDATE;
    IF pk.id IS NULL THEN
        RAISE EXCEPTION 'Vse izbire so že opravljene.';
    END IF;

    UPDATE public.dezurstva SET user_id = pk.user_id
    WHERE id = p_dezurstvo_id AND pool_id = p_pool_id AND user_id IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ta izmena ni prosta.';
    END IF;

    UPDATE public.reception_pick_order
    SET status = 'done', dezurstvo_id = p_dezurstvo_id, picked_at = now()
    WHERE id = pk.id;

    UPDATE public.reception_pools SET status = 'assigning'
    WHERE id = p_pool_id AND status = 'drawn';

    INSERT INTO public.reception_draw_log (pool_id, actor, action, details)
    VALUES (p_pool_id, public.current_base_user_id(), 'pick',
            jsonb_build_object('position', pk.position, 'user_id', pk.user_id, 'dezurstvo_id', p_dezurstvo_id));
END;
$$;

-- "Ni dosegljiv": move whoever is on turn to the end of their round
CREATE OR REPLACE FUNCTION public.skip_reception_pick(p_pool_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    pk public.reception_pick_order;
    last_pos integer;
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za razdeljevanje.';
    END IF;

    SELECT * INTO pk FROM public.reception_pick_order
    WHERE pool_id = p_pool_id AND status = 'pending'
    ORDER BY position LIMIT 1
    FOR UPDATE;
    IF pk.id IS NULL THEN
        RAISE EXCEPTION 'Nihče ni na vrsti.';
    END IF;

    SELECT max(position) INTO last_pos FROM public.reception_pick_order
    WHERE pool_id = p_pool_id AND round = pk.round;
    IF last_pos = pk.position THEN
        RAISE EXCEPTION 'Oseba je zadnja v krogu.';
    END IF;

    UPDATE public.reception_pick_order
    SET position = CASE WHEN id = pk.id THEN last_pos ELSE position - 1 END,
        skip_count = skip_count + (id = pk.id)::integer
    WHERE pool_id = p_pool_id AND position BETWEEN pk.position AND last_pos;

    INSERT INTO public.reception_draw_log (pool_id, actor, action, details)
    VALUES (p_pool_id, public.current_base_user_id(), 'skip',
            jsonb_build_object('user_id', pk.user_id, 'from', pk.position, 'to', last_pos));
END;
$$;

-- Undo the most recent pick: frees its slot and puts that person back on turn
CREATE OR REPLACE FUNCTION public.undo_reception_pick(p_pool_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    pk public.reception_pick_order;
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za razdeljevanje.';
    END IF;

    SELECT * INTO pk FROM public.reception_pick_order
    WHERE pool_id = p_pool_id AND status = 'done'
    ORDER BY picked_at DESC, position DESC LIMIT 1
    FOR UPDATE;
    IF pk.id IS NULL THEN
        RAISE EXCEPTION 'Ni česa razveljaviti.';
    END IF;

    -- only free the slot if nobody changed it since
    UPDATE public.dezurstva SET user_id = NULL
    WHERE id = pk.dezurstvo_id AND user_id = pk.user_id;

    UPDATE public.reception_pick_order
    SET status = 'pending', dezurstvo_id = NULL, picked_at = NULL
    WHERE id = pk.id;

    INSERT INTO public.reception_draw_log (pool_id, actor, action, details)
    VALUES (p_pool_id, public.current_base_user_id(), 'undo',
            jsonb_build_object('position', pk.position, 'dezurstvo_id', pk.dezurstvo_id));
END;
$$;

CREATE OR REPLACE FUNCTION public.publish_reception_pool(p_pool_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za objavo.';
    END IF;

    UPDATE public.reception_pools SET status = 'published', published_at = now()
    WHERE id = p_pool_id AND status IN ('drawn', 'assigning');
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Razpored ni pripravljen za objavo.';
    END IF;

    INSERT INTO public.reception_draw_log (pool_id, actor, action)
    VALUES (p_pool_id, public.current_base_user_id(), 'publish');
END;
$$;

-- ===== 8. Swap market functions =====

-- When a slot changes owner by any path (swap, give-away, manager edit),
-- its open offer and pending bids that use it are no longer valid.
CREATE OR REPLACE FUNCTION public.dezurstvo_owner_changed() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    UPDATE public.dezurstva_bids b SET status = 'rejected'
    FROM public.dezurstva_offers o
    WHERE b.offer_id = o.id AND o.dezurstvo_id = NEW.id
      AND o.status = 'open' AND b.status = 'pending';

    UPDATE public.dezurstva_offers SET status = 'cancelled', closed_at = now()
    WHERE dezurstvo_id = NEW.id AND status = 'open';

    UPDATE public.dezurstva_bids SET status = 'withdrawn'
    WHERE dezurstvo_id = NEW.id AND status = 'pending';

    RETURN NEW;
END;
$$;

CREATE TRIGGER dezurstva_owner_changed
    AFTER UPDATE OF user_id ON public.dezurstva
    FOR EACH ROW WHEN (OLD.user_id IS DISTINCT FROM NEW.user_id)
    EXECUTE FUNCTION public.dezurstvo_owner_changed();

-- Owner puts their future slot up for a swap or a give-away
CREATE OR REPLACE FUNCTION public.offer_dezurstvo(
    p_dezurstvo_id bigint,
    p_kind public.dezurstvo_offer_kind,
    p_target_user_id bigint DEFAULT NULL,
    p_note text DEFAULT NULL
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.current_base_user_id();
    d public.dezurstva;
    new_id bigint;
BEGIN
    SELECT * INTO d FROM public.dezurstva WHERE id = p_dezurstvo_id FOR UPDATE;
    IF d.id IS NULL OR d.user_id IS DISTINCT FROM me THEN
        RAISE EXCEPTION 'To dežurstvo ni tvoje.';
    END IF;
    IF public.dezurstvo_starts_at(d.date, d.slot) <= now() THEN
        RAISE EXCEPTION 'Dežurstvo se je že začelo.';
    END IF;
    IF p_target_user_id = me THEN
        RAISE EXCEPTION 'Dežurstva ne moreš podariti sebi.';
    END IF;

    INSERT INTO public.dezurstva_offers (dezurstvo_id, offered_by, kind, target_user_id, note)
    VALUES (d.id, me, p_kind, p_target_user_id, p_note)
    RETURNING id INTO new_id;
    RETURN new_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_dezurstvo_offer(p_offer_id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    UPDATE public.dezurstva_offers SET status = 'cancelled', closed_at = now()
    WHERE id = p_offer_id AND offered_by = public.current_base_user_id() AND status = 'open';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ponudba ne obstaja ali ni več odprta.';
    END IF;

    UPDATE public.dezurstva_bids SET status = 'rejected'
    WHERE offer_id = p_offer_id AND status = 'pending';
END;
$$;

-- Take a slot someone is giving away (first come, or only the target)
CREATE OR REPLACE FUNCTION public.claim_dezurstvo(p_offer_id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.current_base_user_id();
    o public.dezurstva_offers;
    d public.dezurstva;
BEGIN
    IF NOT public.current_user_has_permission('RECEPTION') THEN
        RAISE EXCEPTION 'Za prevzem dežurstva potrebuješ dovoljenje za recepcijo.';
    END IF;

    SELECT * INTO o FROM public.dezurstva_offers WHERE id = p_offer_id FOR UPDATE;
    IF o.id IS NULL OR o.status <> 'open' OR o.kind <> 'giveaway' THEN
        RAISE EXCEPTION 'Ponudba ni več na voljo.';
    END IF;
    IF o.offered_by = me THEN
        RAISE EXCEPTION 'Svojega dežurstva ne moreš prevzeti.';
    END IF;
    IF o.target_user_id IS NOT NULL AND o.target_user_id <> me THEN
        RAISE EXCEPTION 'To dežurstvo je namenjeno nekomu drugemu.';
    END IF;

    SELECT * INTO d FROM public.dezurstva WHERE id = o.dezurstvo_id FOR UPDATE;
    IF public.dezurstvo_starts_at(d.date, d.slot) <= now() THEN
        RAISE EXCEPTION 'Dežurstvo se je že začelo.';
    END IF;

    UPDATE public.dezurstva_offers SET status = 'completed', closed_at = now(), taken_by = me
    WHERE id = o.id;
    UPDATE public.dezurstva SET user_id = me WHERE id = d.id;
END;
$$;

-- Propose one of my future slots in exchange for an offered one
CREATE OR REPLACE FUNCTION public.bid_dezurstvo(
    p_offer_id bigint,
    p_my_dezurstvo_id bigint,
    p_note text DEFAULT NULL
) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.current_base_user_id();
    o public.dezurstva_offers;
    d public.dezurstva;
    new_id bigint;
BEGIN
    SELECT * INTO o FROM public.dezurstva_offers WHERE id = p_offer_id FOR UPDATE;
    IF o.id IS NULL OR o.status <> 'open' OR o.kind <> 'swap' THEN
        RAISE EXCEPTION 'Ponudba ni več na voljo.';
    END IF;
    IF o.offered_by = me THEN
        RAISE EXCEPTION 'Na svojo ponudbo ne moreš predlagati menjave.';
    END IF;

    SELECT * INTO d FROM public.dezurstva WHERE id = p_my_dezurstvo_id;
    IF d.id IS NULL OR d.user_id IS DISTINCT FROM me THEN
        RAISE EXCEPTION 'Ponudiš lahko samo svoje dežurstvo.';
    END IF;
    IF public.dezurstvo_starts_at(d.date, d.slot) <= now() THEN
        RAISE EXCEPTION 'Dežurstvo se je že začelo.';
    END IF;

    INSERT INTO public.dezurstva_bids (offer_id, bidder_id, dezurstvo_id, note)
    VALUES (o.id, me, d.id, p_note)
    RETURNING id INTO new_id;
    RETURN new_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.withdraw_dezurstvo_bid(p_bid_id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    UPDATE public.dezurstva_bids SET status = 'withdrawn'
    WHERE id = p_bid_id AND bidder_id = public.current_base_user_id() AND status = 'pending';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Predlog ne obstaja ali ni več odprt.';
    END IF;
END;
$$;

-- Owner accepts one proposal: the two slots swap owners in one transaction
CREATE OR REPLACE FUNCTION public.accept_dezurstvo_bid(p_bid_id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.current_base_user_id();
    o public.dezurstva_offers;
    b public.dezurstva_bids;
    mine public.dezurstva;
    theirs public.dezurstva;
BEGIN
    -- lock offer before bid, same order as cancel_dezurstvo_offer
    SELECT o2.* INTO o FROM public.dezurstva_offers o2
    WHERE o2.id = (SELECT offer_id FROM public.dezurstva_bids WHERE id = p_bid_id)
    FOR UPDATE;
    SELECT * INTO b FROM public.dezurstva_bids WHERE id = p_bid_id FOR UPDATE;

    IF o.id IS NULL OR o.offered_by IS DISTINCT FROM me OR o.status <> 'open' THEN
        RAISE EXCEPTION 'Ponudba ni več odprta.';
    END IF;
    IF b.status <> 'pending' THEN
        RAISE EXCEPTION 'Ta predlog ni več veljaven.';
    END IF;

    -- lock both slots in id order so concurrent swaps can't deadlock
    PERFORM 1 FROM public.dezurstva WHERE id IN (o.dezurstvo_id, b.dezurstvo_id) ORDER BY id FOR UPDATE;
    SELECT * INTO mine FROM public.dezurstva WHERE id = o.dezurstvo_id;
    SELECT * INTO theirs FROM public.dezurstva WHERE id = b.dezurstvo_id;

    IF theirs.user_id IS DISTINCT FROM b.bidder_id THEN
        RAISE EXCEPTION 'Ponujeno dežurstvo ni več od te osebe.';
    END IF;
    IF least(public.dezurstvo_starts_at(mine.date, mine.slot),
             public.dezurstvo_starts_at(theirs.date, theirs.slot)) <= now() THEN
        RAISE EXCEPTION 'Eno od dežurstev se je že začelo.';
    END IF;

    UPDATE public.dezurstva_bids
    SET status = CASE WHEN id = b.id THEN 'accepted' ELSE 'rejected' END::public.dezurstvo_bid_status
    WHERE offer_id = o.id AND status = 'pending';
    UPDATE public.dezurstva_offers SET status = 'completed', closed_at = now(), taken_by = b.bidder_id
    WHERE id = o.id;

    -- the trigger cleans up other offers/bids that used either slot
    UPDATE public.dezurstva
    SET user_id = CASE WHEN id = mine.id THEN b.bidder_id ELSE me END
    WHERE id IN (mine.id, theirs.id);
END;
$$;

