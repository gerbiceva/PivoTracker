-- Dežurstva (reception shifts): planned schema, NOT a migration.
-- Matches docs/dezurstva.puml (ER) and docs/dezurstva-menjave.puml (swap flow).
--
-- Flow:
--   1. MANAGE_RECEPTION opens a pool for next month with a deadline.
--   2. Users with RECEPTION apply until closes_at.
--   3. Manager draws the pick order; the month's 4 slots per day are created empty.
--   4. Manager calls people in order and assigns the slot each one picks.
--   5. Manager publishes; from then on users can swap / give away their slots.

-- ===== 1. Permissions and types =====

INSERT INTO public.permission_types (name, display_name) VALUES
  ('RECEPTION', 'Delo na recepciji'),
  ('MANAGE_RECEPTION', 'Upravljanje recepcije')
ON CONFLICT (name) DO NOTHING;

CREATE TYPE public.reception_pool_status AS ENUM ('open', 'drawn', 'assigning', 'published');
CREATE TYPE public.reception_pick_status AS ENUM ('pending', 'done');
CREATE TYPE public.dezurstvo_offer_kind AS ENUM ('swap', 'giveaway');
CREATE TYPE public.dezurstvo_offer_status AS ENUM ('open', 'completed', 'cancelled');
CREATE TYPE public.dezurstvo_bid_status AS ENUM ('pending', 'accepted', 'rejected', 'withdrawn');

-- current user's base_users.id
CREATE OR REPLACE FUNCTION public.current_base_user_id() RETURNS bigint
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path = ''
    AS $$
  SELECT bu.id FROM public.base_users bu WHERE bu.auth = (SELECT auth.uid());
$$;

-- ===== 2. Application pool =====

-- One per month. "Closed" is not stored: a pool is closed once now() > closes_at.
CREATE TABLE IF NOT EXISTS public.reception_pools (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    month date NOT NULL UNIQUE CHECK (extract(day FROM month) = 1),
    opens_at timestamp with time zone DEFAULT now() NOT NULL,
    closes_at timestamp with time zone NOT NULL,
    status public.reception_pool_status DEFAULT 'open' NOT NULL,
    seed bigint,
    drawn_at timestamp with time zone,
    published_at timestamp with time zone,
    created_by bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    drawn_by bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    CHECK (closes_at > opens_at)
);

CREATE TABLE IF NOT EXISTS public.reception_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    pool_id bigint NOT NULL REFERENCES public.reception_pools(id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    note text,
    UNIQUE (pool_id, user_id)
);

-- ===== 3. Shifts =====

-- One row per 6h slot: 0 = 00-06, 1 = 06-12, 2 = 12-18, 3 = 18-24.
-- Created empty by the draw; user_id null = free.
CREATE TABLE IF NOT EXISTS public.dezurstva (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    date date NOT NULL,
    slot smallint NOT NULL CHECK (slot BETWEEN 0 AND 3),
    pool_id bigint REFERENCES public.reception_pools(id) ON UPDATE CASCADE ON DELETE SET NULL,
    user_id bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_by bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    note text,
    UNIQUE (date, slot)
);
CREATE INDEX IF NOT EXISTS dezurstva_user_id_idx ON public.dezurstva (user_id);
CREATE INDEX IF NOT EXISTS dezurstva_pool_id_idx ON public.dezurstva (pool_id);

CREATE OR REPLACE FUNCTION public.dezurstvo_starts_at(p_date date, p_slot smallint) RETURNS timestamptz
    LANGUAGE sql STABLE
    SET search_path = ''
    AS $$
  SELECT (p_date + p_slot * interval '6 hours') AT TIME ZONE 'Europe/Ljubljana';
$$;

-- What pages read: name and room come from joins, never stored twice
CREATE OR REPLACE VIEW public.dezurstva_view
WITH (security_invoker = true) AS
SELECT d.id, d.date, d.slot, d.pool_id, d.user_id,
       u.name, u.surname, r.room, d.note
FROM public.dezurstva d
LEFT JOIN public.base_users u ON u.id = d.user_id
LEFT JOIN public.residents r ON r.id = u.resident;

-- ===== 4. Pick order and log =====

CREATE TABLE IF NOT EXISTS public.reception_pick_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id bigint NOT NULL REFERENCES public.reception_pools(id) ON UPDATE CASCADE ON DELETE CASCADE,
    position integer NOT NULL CHECK (position > 0),
    round smallint NOT NULL CHECK (round > 0),
    user_id bigint NOT NULL REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    status public.reception_pick_status DEFAULT 'pending' NOT NULL,
    skip_count smallint DEFAULT 0 NOT NULL,
    -- the slot this pick got
    dezurstvo_id bigint REFERENCES public.dezurstva(id) ON UPDATE CASCADE ON DELETE SET NULL,
    picked_at timestamp with time zone,
    -- deferred so skip/move can shift positions inside one statement
    UNIQUE (pool_id, position) DEFERRABLE INITIALLY DEFERRED
);

-- Every draw, redraw, manual reorder, skip, pick and undo, for accountability
CREATE TABLE IF NOT EXISTS public.reception_draw_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    pool_id bigint NOT NULL REFERENCES public.reception_pools(id) ON UPDATE CASCADE ON DELETE CASCADE,
    actor bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    action text NOT NULL CHECK (action IN ('draw', 'redraw', 'move', 'remove', 'skip', 'pick', 'undo', 'publish')),
    seed bigint,
    details jsonb
);
CREATE INDEX IF NOT EXISTS reception_draw_log_pool_id_idx ON public.reception_draw_log (pool_id);

-- ===== 5. Swap market =====

CREATE TABLE IF NOT EXISTS public.dezurstva_offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    dezurstvo_id bigint NOT NULL REFERENCES public.dezurstva(id) ON UPDATE CASCADE ON DELETE CASCADE,
    offered_by bigint NOT NULL REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    kind public.dezurstvo_offer_kind NOT NULL,
    -- give-away to one specific person; null = anyone with RECEPTION
    target_user_id bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    status public.dezurstvo_offer_status DEFAULT 'open' NOT NULL,
    note text,
    closed_at timestamp with time zone,
    taken_by bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    CHECK (kind = 'giveaway' OR target_user_id IS NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS dezurstva_offers_one_open_idx
    ON public.dezurstva_offers (dezurstvo_id) WHERE status = 'open';

CREATE TABLE IF NOT EXISTS public.dezurstva_bids (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    offer_id bigint NOT NULL REFERENCES public.dezurstva_offers(id) ON UPDATE CASCADE ON DELETE CASCADE,
    bidder_id bigint NOT NULL REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- the slot the bidder gives in exchange
    dezurstvo_id bigint NOT NULL REFERENCES public.dezurstva(id) ON UPDATE CASCADE ON DELETE CASCADE,
    status public.dezurstvo_bid_status DEFAULT 'pending' NOT NULL,
    note text
);
CREATE UNIQUE INDEX IF NOT EXISTS dezurstva_bids_one_pending_idx
    ON public.dezurstva_bids (offer_id, dezurstvo_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS dezurstva_bids_dezurstvo_id_idx ON public.dezurstva_bids (dezurstvo_id);

