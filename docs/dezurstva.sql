    FOR INSERT TO authenticated
    WITH CHECK (
        user_id = public.current_base_user_id()
        AND public.current_user_has_permission('RECEPTION')
        AND EXISTS (SELECT 1 FROM public.reception_pools p
                    WHERE p.id = pool_id AND p.status = 'open'
                      AND now() BETWEEN p.opens_at AND p.closes_at)
    );
CREATE POLICY reception_applications_withdraw ON public.reception_applications
    FOR DELETE TO authenticated
    USING (
        user_id = public.current_base_user_id()
        AND EXISTS (SELECT 1 FROM public.reception_pools p
                    WHERE p.id = pool_id AND p.status = 'open' AND now() <= p.closes_at)
