-- Dežurstva, step 1: sign-ups for the draw.
-- The namestnik (MANAGE_RECEPTION) schedules the draw for a month. Everyone
-- with RECEPTION then sees a notification on the homepage and can sign up or
-- withdraw until the draw. The draw itself, allotment and swaps come later
-- (plan in docs/dezurstva.sql).
--
-- Notifications are generic: one row per notification, what each user did
-- with it lives in notification_dismissals. The button is one of a fixed set
-- of actions the app knows how to handle, never a function name from the row.

INSERT INTO public.permission_types (name, display_name) VALUES
  ('RECEPTION', 'Dežurstvo na recepciji'),
  ('MANAGE_RECEPTION', 'Upravljanje dežurstev')
ON CONFLICT (name) DO NOTHING;

-- 1. Sign-up pools

-- later steps use the other values
CREATE TYPE public.reception_pool_status AS ENUM ('open', 'drawn', 'assigning', 'published');

CREATE TABLE IF NOT EXISTS public.reception_pools (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    created_by bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    -- first day of the month the shifts are for
    month date NOT NULL UNIQUE CHECK (extract(day FROM month) = 1),
    -- when the draw happens; sign-ups are open until then
    closes_at timestamp with time zone NOT NULL,
    status public.reception_pool_status DEFAULT 'open' NOT NULL
);
ALTER TABLE public.reception_pools OWNER TO postgres;
COMMENT ON TABLE public.reception_pools IS 'One per month: sign-ups for the dežurstva draw, open until closes_at.';

CREATE TABLE IF NOT EXISTS public.reception_applications (
    pool_id bigint NOT NULL REFERENCES public.reception_pools(id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    PRIMARY KEY (pool_id, user_id)
);
ALTER TABLE public.reception_applications OWNER TO postgres;
CREATE INDEX IF NOT EXISTS reception_applications_user_id_idx ON public.reception_applications (user_id);

-- 2. Notifications

CREATE TYPE public.notification_audience AS ENUM ('all', 'permission');
-- none: no button, link: open action_data.to inside the app,
-- reception_apply: sign up / withdraw for pool action_data.pool_id
CREATE TYPE public.notification_action AS ENUM ('none', 'link', 'reception_apply');

CREATE TABLE IF NOT EXISTS public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    -- null = created by the system
    created_by bigint REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    title text NOT NULL CHECK (length(title) BETWEEN 1 AND 120),
    body text CHECK (length(body) <= 1000),
    tone text DEFAULT 'info' NOT NULL CHECK (tone IN ('info', 'important', 'success')),
    audience public.notification_audience DEFAULT 'all' NOT NULL,
    audience_permission text,
    starts_at timestamp with time zone DEFAULT now() NOT NULL,
    -- null = until deleted
    expires_at timestamp with time zone,
    dismissible boolean DEFAULT true NOT NULL,
    action public.notification_action DEFAULT 'none' NOT NULL,
    action_label text,
    action_data jsonb,
    -- what created it, so the system can update or remove it with its source
    source_type text,
    source_id bigint,
    CHECK (audience <> 'permission' OR audience_permission IS NOT NULL),
    CHECK (action = 'none' OR action_label IS NOT NULL)
);
ALTER TABLE public.notifications OWNER TO postgres;
COMMENT ON TABLE public.notifications IS 'Homepage notifications; per-user state is in notification_dismissals.';
CREATE INDEX IF NOT EXISTS notifications_source_idx ON public.notifications (source_type, source_id);

CREATE TABLE IF NOT EXISTS public.notification_dismissals (
    notification_id bigint NOT NULL REFERENCES public.notifications(id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.base_users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    dismissed_at timestamp with time zone DEFAULT now() NOT NULL,
    PRIMARY KEY (notification_id, user_id)
);
ALTER TABLE public.notification_dismissals OWNER TO postgres;
CREATE INDEX IF NOT EXISTS notification_dismissals_user_id_idx ON public.notification_dismissals (user_id);

CREATE OR REPLACE FUNCTION public.notification_is_for_current_user(
    p_audience public.notification_audience,
    p_permission text
) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path = ''
    AS $$
  SELECT p_audience = 'all'
      OR (p_audience = 'permission' AND public.current_user_has_permission(p_permission));
$$;
ALTER FUNCTION public.notification_is_for_current_user(public.notification_audience, text) OWNER TO postgres;

