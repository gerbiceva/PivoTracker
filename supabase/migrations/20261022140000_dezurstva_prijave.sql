    public.notifications, public.notification_dismissals TO service_role;

-- 4. Scheduling the draw (MANAGE_RECEPTION)

-- "Žreb bo v sredo, 28. 10. ob 20:00. ..." in Ljubljana time
CREATE OR REPLACE FUNCTION public.reception_pool_notice(p_closes_at timestamptz)
RETURNS text
    LANGUAGE sql STABLE
    SET search_path = ''
    AS $$
  SELECT format(
      'Žreb bo %s, %s ob %s. Do takrat se lahko prijaviš ali odjaviš.',
      (ARRAY['v nedeljo', 'v ponedeljek', 'v torek', 'v sredo',
             'v četrtek', 'v petek', 'v soboto'])[extract(dow FROM l)::int + 1],
      to_char(l, 'FMDD. FMMM.'),
      to_char(l, 'HH24:MI'))
  FROM (SELECT p_closes_at AT TIME ZONE 'Europe/Ljubljana' AS l) t;
$$;
ALTER FUNCTION public.reception_pool_notice(timestamptz) OWNER TO postgres;

CREATE OR REPLACE FUNCTION public.month_name_sl(p_month date)
RETURNS text
    LANGUAGE sql IMMUTABLE
    SET search_path = ''
    AS $$
  SELECT (ARRAY['januar', 'februar', 'marec', 'april', 'maj', 'junij', 'julij',
                'avgust', 'september', 'oktober', 'november', 'december'])[extract(month FROM p_month)::int];
$$;
ALTER FUNCTION public.month_name_sl(date) OWNER TO postgres;

-- Opens sign-ups for a month until the draw and notifies everyone with RECEPTION
CREATE OR REPLACE FUNCTION public.open_reception_pool(p_month date, p_closes_at timestamptz)
RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.get_current_base_user_id();
    v_month date := date_trunc('month', p_month)::date;
    new_id bigint;
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za razpis žreba.';
    END IF;
    IF p_closes_at <= now() THEN
        RAISE EXCEPTION 'Čas žreba mora biti v prihodnosti.';
    END IF;
    IF v_month < date_trunc('month', now() AT TIME ZONE 'Europe/Ljubljana')::date THEN
        RAISE EXCEPTION 'Ta mesec je že mimo.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.reception_pools WHERE month = v_month) THEN
        RAISE EXCEPTION 'Žreb za % je že razpisan.', public.month_name_sl(v_month);
    END IF;

    INSERT INTO public.reception_pools (created_by, month, closes_at)
    VALUES (me, v_month, p_closes_at)
    RETURNING id INTO new_id;

    INSERT INTO public.notifications (
        created_by, title, body, audience, audience_permission, expires_at,
        action, action_label, action_data, source_type, source_id)
    VALUES (
        me,
        format('Prijave na žreb za dežurstva: %s', public.month_name_sl(v_month)),
        public.reception_pool_notice(p_closes_at),
        'permission', 'RECEPTION', p_closes_at,
        'reception_apply', 'Prijavi se', jsonb_build_object('pool_id', new_id),
        'reception_pool', new_id);

    RETURN new_id;
END;
$$;
ALTER FUNCTION public.open_reception_pool(date, timestamptz) OWNER TO postgres;

-- Moves the draw; the notification follows. Moving it into the future again
-- reopens sign-ups.
CREATE OR REPLACE FUNCTION public.update_reception_pool_time(p_pool_id bigint, p_closes_at timestamptz)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za urejanje žreba.';
    END IF;
    IF p_closes_at <= now() THEN
        RAISE EXCEPTION 'Čas žreba mora biti v prihodnosti.';
    END IF;

    UPDATE public.reception_pools SET closes_at = p_closes_at
    WHERE id = p_pool_id AND status = 'open';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Žreba ni več mogoče prestaviti.';
    END IF;

    UPDATE public.notifications
    SET body = public.reception_pool_notice(p_closes_at), expires_at = p_closes_at
    WHERE source_type = 'reception_pool' AND source_id = p_pool_id;
END;
$$;
ALTER FUNCTION public.update_reception_pool_time(bigint, timestamptz) OWNER TO postgres;

-- Removes the pool, its sign-ups and its notification
CREATE OR REPLACE FUNCTION public.cancel_reception_pool(p_pool_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za preklic žreba.';
    END IF;

    DELETE FROM public.reception_pools WHERE id = p_pool_id AND status = 'open';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Žreba ni več mogoče preklicati.';
    END IF;

    DELETE FROM public.notifications
    WHERE source_type = 'reception_pool' AND source_id = p_pool_id;
END;
$$;
ALTER FUNCTION public.cancel_reception_pool(bigint) OWNER TO postgres;

CREATE OR REPLACE FUNCTION public.get_reception_applicants(p_pool_id bigint)
RETURNS TABLE (
    user_id bigint,
    name text,
    surname text,
    room bigint,
    applied_at timestamptz
)
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    IF NOT public.current_user_has_permission('MANAGE_RECEPTION') THEN
        RAISE EXCEPTION 'Nimaš pravic za pregled prijav.';
    END IF;

    RETURN QUERY
    SELECT a.user_id, u.name, u.surname, r.room, a.created_at
    FROM public.reception_applications a
    JOIN public.base_users u ON u.id = a.user_id
    LEFT JOIN public.residents r ON r.id = u.resident
    WHERE a.pool_id = p_pool_id
    ORDER BY a.created_at;
END;
$$;
ALTER FUNCTION public.get_reception_applicants(bigint) OWNER TO postgres;

-- 5. Signing up (RECEPTION)

CREATE OR REPLACE FUNCTION public.apply_to_reception_pool(p_pool_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.get_current_base_user_id();
BEGIN
    IF me IS NULL OR NOT public.current_user_has_permission('RECEPTION') THEN
        RAISE EXCEPTION 'Za prijavo na dežurstva potrebuješ dovoljenje za recepcijo.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.reception_pools
                   WHERE id = p_pool_id AND status = 'open' AND closes_at > now()) THEN
        RAISE EXCEPTION 'Prijave na ta žreb so zaprte.';
    END IF;

    INSERT INTO public.reception_applications (pool_id, user_id)
    VALUES (p_pool_id, me)
    ON CONFLICT (pool_id, user_id) DO NOTHING;
END;
$$;
ALTER FUNCTION public.apply_to_reception_pool(bigint) OWNER TO postgres;

CREATE OR REPLACE FUNCTION public.withdraw_from_reception_pool(p_pool_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.reception_pools
                   WHERE id = p_pool_id AND status = 'open' AND closes_at > now()) THEN
        RAISE EXCEPTION 'Prijave na ta žreb so zaprte, odjava ni več mogoča.';
    END IF;

    DELETE FROM public.reception_applications
    WHERE pool_id = p_pool_id AND user_id = public.get_current_base_user_id();
END;
$$;
ALTER FUNCTION public.withdraw_from_reception_pool(bigint) OWNER TO postgres;

-- 6. Reading and closing notifications

-- Active notifications for the current user that they haven't closed.
-- action_state carries what the button needs, e.g. whether they signed up.
CREATE OR REPLACE FUNCTION public.get_my_notifications()
RETURNS TABLE (
    id bigint,
    created_at timestamptz,
    title text,
    body text,
    tone text,
    dismissible boolean,
    action public.notification_action,
    action_label text,
    action_data jsonb,
    expires_at timestamptz,
    action_state jsonb
)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path = ''
    AS $$
  WITH me AS (SELECT public.get_current_base_user_id() AS id)
  SELECT n.id, n.created_at, n.title, n.body, n.tone, n.dismissible,
         n.action, n.action_label, n.action_data, n.expires_at,
         CASE n.action
             WHEN 'reception_apply' THEN (
                 SELECT jsonb_build_object(
                     'pool_id', p.id,
                     'month', p.month,
                     'closes_at', p.closes_at,
                     'applied', EXISTS (SELECT 1 FROM public.reception_applications a
                                        WHERE a.pool_id = p.id AND a.user_id = me.id),
                     'count', (SELECT count(*) FROM public.reception_applications a
                               WHERE a.pool_id = p.id))
                 FROM public.reception_pools p
                 WHERE p.id = (n.action_data ->> 'pool_id')::bigint)
         END
  FROM public.notifications n, me
  WHERE me.id IS NOT NULL
    AND public.notification_is_for_current_user(n.audience, n.audience_permission)
    AND n.starts_at <= now()
    AND (n.expires_at IS NULL OR n.expires_at > now())
    AND NOT EXISTS (SELECT 1 FROM public.notification_dismissals d
                    WHERE d.notification_id = n.id AND d.user_id = me.id)
  ORDER BY n.created_at DESC;
$$;
ALTER FUNCTION public.get_my_notifications() OWNER TO postgres;

CREATE OR REPLACE FUNCTION public.dismiss_notification(p_notification_id bigint)
RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path = ''
    AS $$
DECLARE
    me bigint := public.get_current_base_user_id();
BEGIN
    IF me IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.notifications n
        WHERE n.id = p_notification_id AND n.dismissible
          AND public.notification_is_for_current_user(n.audience, n.audience_permission)
    ) THEN
        RAISE EXCEPTION 'Tega obvestila ni mogoče zapreti.';
    END IF;

    INSERT INTO public.notification_dismissals (notification_id, user_id)
    VALUES (p_notification_id, me)
    ON CONFLICT (notification_id, user_id) DO NOTHING;
END;
$$;
ALTER FUNCTION public.dismiss_notification(bigint) OWNER TO postgres;

-- undo for a close
CREATE OR REPLACE FUNCTION public.undismiss_notification(p_notification_id bigint)
RETURNS void
    LANGUAGE sql SECURITY DEFINER
    SET search_path = ''
    AS $$
  DELETE FROM public.notification_dismissals
  WHERE notification_id = p_notification_id
    AND user_id = public.get_current_base_user_id();
$$;
ALTER FUNCTION public.undismiss_notification(bigint) OWNER TO postgres;

